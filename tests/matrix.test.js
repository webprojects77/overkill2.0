const {load,harness}=require("./helpers");
const {get}=load(["src/core.js","src/matrix.js"]);
const T=harness(),LA=get("LA"),CalcError=get("CalcError");
const A=LA.parse("1 2; 3 4");
T.near("det",LA.det(A),-2);T.eq("posto 1",LA.rank(LA.parse("1 2; 2 4")),1);T.eq("posto 2",LA.rank(A),2);
const I=LA.mul(A,LA.inv(A).X);T.near("A·A⁻¹ [0][0]",I[0][0],1);T.near("A·A⁻¹ [0][1]",I[0][1],0,1e-12);T.near("A·A⁻¹ [1][1]",I[1][1],1);
const s=LA.solve(LA.parse("2 1; 1 3"),LA.parse("3; 5"));T.near("x0",s.X[0][0],0.8);T.near("x1",s.X[1][0],1.4);T.ok("resíduo pequeno",s.res<1e-12,s.res);
T.near("det diagonal",LA.det(LA.parse("2 0 0; 0 3 0; 0 0 4")),24);
T.near("transposta",LA.T(LA.parse("1 2 3; 4 5 6"))[2][1],6);
T.near("A×B",LA.mul(LA.parse("1 2; 3 4"),LA.parse("5; 6"))[1][0],39);
T.ok("condicionamento alto avisa",LA.inv(LA.parse("1 1; 1 1.0000000001")).cond>1e9);
T.throws("inversa singular",()=>LA.inv(LA.parse("1 2; 2 4")),CalcError);
T.throws("dimensões do produto",()=>LA.mul(LA.parse("1 2 3"),LA.parse("1 2 3")),CalcError);
T.throws("det não quadrada",()=>LA.det(LA.parse("1 2 3; 4 5 6")),CalcError);
T.throws("linhas desiguais",()=>LA.parse("1 2; 3"),CalcError);
T.throws("sistema singular",()=>LA.solve(LA.parse("1 2; 2 4"),LA.parse("1; 2")),CalcError);
T.throws("limite 12x12",()=>LA.parse(Array.from({length:13},()=>"1").join(";")),CalcError);
T.near("expressão em célula",LA.parse("1+1 2pi")[0][0],2);
T.done("matrizes");
