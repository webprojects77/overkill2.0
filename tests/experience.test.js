const fs=require("fs"),path=require("path");
const {load,harness,root}=require("./helpers");
const T=harness();
const {get}=load(["src/experience.js"]);
const XP=get("XP");
const MOD=Object.keys(XP.MODULES),EXP=Object.keys(XP.EXPERIENCES);
EXP.forEach(k=>{
  const e=XP.EXPERIENCES[k];
  T.ok("perfil "+k+" tem todas as abas",[...e.tabs].sort().join()===["calc","gr","mat","tl","nb"].sort().join(),e.tabs);
  T.ok("perfil "+k+" tem todos os cartões",[...e.cards].sort().join()===MOD.slice().sort().join(),e.cards);
  T.ok("perfil "+k+" tem ferramenta válida",["un","bs","fp","cl","st","sy","al"].includes(e.tool),e.tool);
});
T.ok("Oracle marcado como em breve",XP.MODULES.oracle.soon===true);
T.ok("Oracle não pode ser favorito",XP.normalizePrefs({favs:["oracle","calc"]}).favs.join()==="calc");
const d=XP.normalizePrefs(null);
T.eq("padrão exp",d.exp,"explore");T.eq("padrão tema",d.theme,"graphite");T.eq("padrão densidade",d.density,"comfortable");
T.ok("padrão não visto",d.seen===false&&d.chosen===false);T.ok("padrão favorito calc",d.favs.join()==="calc");
const bad=XP.normalizePrefs({exp:"hack",theme:"<script>",density:"x",seen:"sim",chosen:1,favs:["calc","calc","nope",42]});
T.eq("exp inválido cai no padrão",bad.exp,"explore");T.eq("tema inválido cai no padrão",bad.theme,"graphite");
T.eq("densidade inválida cai no padrão",bad.density,"comfortable");T.ok("seen precisa ser booleano true",bad.seen===false&&bad.chosen===false);
T.eq("favoritos sem duplicatas e válidos",bad.favs.join(),"calc");
T.ok("favoritos limitados a 8",XP.normalizePrefs({favs:MOD.slice(0,5).concat(["a","b","c","d","e"])}).favs.length<=8);
T.ok("normalizePrefs de objeto não-array em favs",XP.normalizePrefs({favs:"calc"}).favs.join()==="calc");
const css=fs.readFileSync(path.join(root,"src/style.css"),"utf8");
["graphite","ember","porcelain","midnight"].forEach(t=>T.ok("CSS tem tema "+t,css.includes('html[data-theme="'+t+'"]')));
T.ok("CSS tem densidade compacta",css.includes('html[data-density="compact"]'));
const html=fs.readFileSync(path.join(root,"index.html"),"utf8");
T.ok("tema padrão no HTML é graphite",html.includes('data-theme="graphite"'));
T.done("experiência");
